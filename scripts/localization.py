#!/usr/bin/env python3
"""翻訳リソースと英語の取り込みガイドを生成・検証する。"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
PLACEHOLDER = re.compile(r"\{[0-9]+\}")


def translation_resources(catalog):
    resources = {}
    for language in ("ja", "en"):
        lines = ["/* Generated by scripts/localization.py. Edit Localization/Localizable.xcstrings. */"]
        for key, entry in sorted(catalog["strings"].items()):
            try:
                unit = entry["localizations"][language]["stringUnit"]
            except KeyError as error:
                raise ValueError(f"Missing translation: {language}: {key}") from error
            value = unit["value"]
            if not value or unit["state"] != "translated":
                raise ValueError(f"Missing translation: {language}: {key}")
            if set(PLACEHOLDER.findall(key)) != set(PLACEHOLDER.findall(value)):
                raise ValueError(f"Placeholder mismatch: {language}: {key}")
            lines.append(f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};")
        resources[Path(f"Sources/DevSwitcher/Resources/{language}.lproj/Localizable.strings")] = "\n".join(lines) + "\n"
    return resources


def import_guide(schema):
    return (
        "# Create Dev Switcher import JSON\n\n"
        "Create UTF-8 schemaVersion 4 JSON for the environments specified by the user. "
        "The user will review it before adding new environments; import does not start anything. "
        "Ask about unspecified commands, arguments, paths, and startup policies instead of guessing. "
        "Do not read .env, .env.*, or .envrc; do not start services, install dependencies, "
        "or run database migration, reset, or seed operations.\n\n"
        + schema[schema.index("## General rules"):]
    )


def synchronize(root, *, check):
    catalog = json.loads((root / "Localization/Localizable.xcstrings").read_text(encoding="utf-8"))
    # 全入力の検証が済むまでは、生成済みファイルを1つも書き換えない。
    resources = translation_resources(catalog)
    resources[Path("Sources/DevSwitcher/Resources/ProjectImportGuide.en.md")] = import_guide(
        (root / "docs/en/SCHEMA.md").read_text(encoding="utf-8")
    )
    for path, content in resources.items():
        destination = root / path
        if check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != content:
                raise ValueError(f"Outdated resource: {destination}. Run python3 scripts/localization.py")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8")
    print(f"Validated {len(catalog['strings'])} messages in Japanese and English, and the English import guide.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="変更せず生成物との一致を検証する")
    args = parser.parse_args()
    synchronize(ROOT, check=args.check)


if __name__ == "__main__":
    main()
